def dep_bound(V, R, alpha=0.05):
    """Dependence-robust one-sided zero-discordance bound (equal F_v, exact; q^R term included):
    solve [(1-q)^R + q^R]^V = alpha for q in [0, 1/2], return 2q(1-q)."""
    target = alpha ** (1.0 / V)
    lo, hi = 0.0, 0.5
    for _ in range(200):
        mid = (lo + hi) / 2
        if (1 - mid) ** R + mid ** R > target:
            lo = mid
        else:
            hi = mid
    q = (lo + hi) / 2
    return 2 * q * (1 - q)


