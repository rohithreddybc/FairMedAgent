        claim("N per action range (main)", _na, "per action the count ranges $%d$--$%d$" % (min(_na[k] for k in per5), max(_na[k] for k in per5)))
        claim("N from six-action floor", ceil(n_needed), ("gives $%d$" % ceil(n_needed), "$%d$ vignettes" % ceil(n_needed)))

